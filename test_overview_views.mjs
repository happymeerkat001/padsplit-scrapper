import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const ids = ['overview-summary','overview-notes','occupancy-section','task-sync','content','climate-section','system-health','view-title','view-description'];
const nodes=Object.fromEntries(ids.map(id=>[id,{hidden:false,textContent:''}]));
const events={};
const context={document:{getElementById:id=>nodes[id],title:''},location:{hash:''},window:{addEventListener:(name,fn)=>events[name]=fn}};
vm.runInNewContext(readFileSync('docs/overview-views.js','utf8'),context);
assert.equal(nodes['overview-summary'].hidden,false);
assert.equal(nodes['climate-section'].hidden,true);
context.location.hash='#content'; events.hashchange();
assert.equal(nodes.content.hidden,false); assert.equal(nodes['task-sync'].hidden,false);
assert.equal(nodes['overview-summary'].hidden,true); assert.equal(nodes['view-title'].textContent,'Tasks');
context.location.hash='#climate-section'; events.hashchange();
assert.equal(nodes.content.hidden,true); assert.equal(nodes['climate-section'].hidden,false);
context.location.hash=''; events.hashchange();
assert.equal(nodes['overview-summary'].hidden,false); assert.equal(nodes['overview-notes'].hidden,false);
console.log('overview routes preserve mounted task and climate sections');

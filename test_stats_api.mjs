import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={};vm.createContext(context);
vm.runInContext(readFileSync('docs/stats-api.js','utf8'),context);
const parse=context.parseReportResponse;
const valid=parse({id:'latest',json:'{"scraped_at":"2026-01-01T00:00:00Z","kpis":{"occupancy_pct":0,"listed":4}}',observed_at:'2026-01-02T00:00:00Z'});
assert.equal(valid.metrics.occupancy_pct,0);
assert.equal(valid.metrics.listed,4);
assert.equal(valid.metrics.rooms_over_14d,undefined);
assert.equal(valid.observedAt,'2026-01-02T00:00:00Z');
assert.equal(context.reportFreshness(valid,new Date('2026-01-05T00:00:00Z')).state,'stale');
assert.equal(context.reportFreshness(parse({id:'latest',json:'{"run_status":{"state":"degraded"},"kpis":{}}',observed_at:null}),new Date()).state,'stale');
assert.throws(()=>parse({id:'latest',json:'bad',observed_at:null}));
assert.throws(()=>parse({id:'other',json:'{}',observed_at:null}));
const history=context.parseHistoryResponse({id:'monthly_history',json:'{"updated_at":"2026-01-01T00:00:00Z","months":[{"month":"2026-01","occupancy_pct":0}]}',observed_at:null});
assert.equal(history.months[0].occupancy_pct,0);
assert.throws(()=>context.parseHistoryResponse({id:'monthly_history',json:'{"months":null}',observed_at:null}));
const inputs={occupancy_pct:90,avg_tenure_days:180,rooms_over_14d:2,listed_count:4,rooms_over_21d:2,avg_flip_days:4,flip_rooms_over_5d:1,open_tickets:4,tickets_over_7d:3,tickets_over_14d:3,daily_calls:5,todo_completion:5,ownership:5,other_hustle:5};
const estimate=context.calculateManualScore(inputs);
assert.equal(estimate.score,125);
assert.equal(estimate.payout,300000);
assert.equal(estimate.bonus,60);
assert.equal(estimate.penalty,10);
assert.ok(estimate.bonuses.some(item=>item.label==='occupancy >= 90%'&&item.points===20));
assert.ok(estimate.penalties.some(item=>item.label==='open tickets > 14d'&&item.count===3&&item.points===-6));
const neutral=context.calculateManualScore({...inputs,occupancy_pct:75,avg_tenure_days:152,rooms_over_21d:0,flip_rooms_over_5d:0,tickets_over_14d:0,daily_calls:0,todo_completion:0,ownership:0,other_hustle:0});
assert.equal(neutral.score,80);
assert.equal(neutral.payout,80000);
assert.throws(()=>context.calculateManualScore({...inputs,occupancy_pct:''}));
assert.throws(()=>context.calculateManualScore({...inputs,rooms_over_21d:-1}));
assert.throws(()=>context.calculateManualScore({...inputs,daily_calls:6}));
assert.throws(()=>context.calculateManualScore({...inputs,listed_count:-1}));
const defaults=context.manualScoreDefaults({occupancy_pct:0,avg_tenure_days:180,vacancy_rooms:[{days_listed:22},{days_listed:21}],flip_rooms:[{days_in_flip:6}],tickets_over_14d:2,subjective_score:12});
assert.equal(defaults.occupancy_pct,0);assert.equal(defaults.rooms_over_21d,1);assert.equal(defaults.flip_rooms_over_5d,1);
assert.equal(defaults.daily_calls,5);assert.equal(defaults.todo_completion,5);assert.equal(defaults.ownership,2);assert.equal(defaults.other_hustle,0);
assert.equal(context.manualScoreDefaults({}).occupancy_pct,undefined);
assert.equal(context.manualScoreDefaults({vacancy_rooms:[{}]}).rooms_over_21d,undefined);
const made=[];class FakeChart { constructor(node,config){this.node=node;this.config=config;made.push(this);} destroy(){this.destroyed=true;} }
const fakeDocument={getElementById:id=>({id})};
const charts=context.createHistoryCharts(fakeDocument,{months:[{month:'2026-02',score:90,occupancy_pct:85,avg_flip_days:4,avg_tenure_days:160},{month:'2026-01',score:80,occupancy_pct:75,avg_flip_days:6,avg_tenure_days:140}]},FakeChart);
assert.equal(made.length,4);assert.equal(made[0].config.type,'line');assert.equal(made[1].config.type,'bar');
assert.equal(made[0].config.data.labels[0],'2026-01');assert.equal(made[0].config.data.datasets[1].data[0],87.5);
assert.equal(made[1].config.data.datasets[0].data[1],190000);
assert.match(made[1].config.options.plugins.tooltip.callbacks.label({dataIndex:1}),/190,000/);
charts.destroy();assert.ok(made.every(chart=>chart.destroyed));
console.log('Report parser preserves missing vs zero and identifies stale/degraded data');

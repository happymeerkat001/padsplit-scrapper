import assert from 'node:assert/strict';import {readFileSync} from 'node:fs';import vm from 'node:vm';
const context={};vm.createContext(context);vm.runInContext(readFileSync('docs/overview-api-access.js','utf8'),context);
const user={uid:'owner1'};
assert.equal(context.classifyOverviewIdentity(user,{uid:'owner1',role:'owner',properties:[]}).role,'owner');
assert.equal(context.classifyOverviewIdentity(user,{uid:'owner1',role:'viewer',properties:['p1']}).role,'viewer');
assert.equal(context.classifyOverviewIdentity(user,{uid:'other',role:'owner',properties:[]}),null);
assert.equal(context.classifyOverviewIdentity(user,{uid:'owner1',role:'admin',properties:[]}),null);
assert.equal(context.classifyOverviewIdentity(user,{uid:'owner1',role:'viewer',properties:'p1'}),null);
let onData,onError,stopCount=0,invalid=0;
const api={poll:(_load,data,error,interval)=>{assert.equal(interval,30000);onData=data;onError=error;return ()=>stopCount++}};
const original={uid:'owner1',role:'viewer',properties:['p2','p1']};
const stop=context.startOverviewAccessWatch({api,user,identity:original,onInvalid:()=>invalid++});
onData({uid:'owner1',role:'viewer',properties:['p1','p2']});assert.equal(invalid,0);
onData({uid:'owner1',role:'viewer',properties:['p1']});assert.equal(invalid,1);
onError(new Error('unavailable'));assert.equal(invalid,2);stop();onData({uid:'owner1',role:'viewer',properties:[]});assert.equal(invalid,2);assert.equal(stopCount,1);
const elements=Object.fromEntries(['overview-notes','notes-textarea','notes-save-btn','notes-copy-btn'].map(id=>[id,{hidden:false,disabled:false,dataset:{}}]));
const document={getElementById:id=>elements[id]};
context.applyOverviewNotesAccess(document,{signedIn:true,apiMode:true,role:'viewer'});
assert.equal(elements['overview-notes'].hidden,true);assert.equal(elements['notes-textarea'].disabled,true);
assert.equal(elements['overview-notes'].dataset.notesAllowed,'false');
context.applyOverviewNotesAccess(document,{signedIn:true,apiMode:true,role:'owner'});
assert.equal(elements['overview-notes'].hidden,false);assert.equal(elements['notes-textarea'].disabled,false);
context.applyOverviewNotesAccess(document,{signedIn:true,apiMode:true,role:'owner',overviewVisible:false});assert.equal(elements['overview-notes'].hidden,true);
context.applyOverviewNotesAccess(document,{signedIn:false,apiMode:true,role:null});
assert.equal(elements['overview-notes'].hidden,true);assert.equal(elements['notes-save-btn'].disabled,true);
context.applyOverviewNotesAccess(document,{signedIn:true,apiMode:false,role:null});
assert.equal(elements['overview-notes'].hidden,false);assert.equal(elements['notes-textarea'].disabled,false);
const page=readFileSync('docs/index.html','utf8');assert.match(page,/classifyOverviewIdentity\(user,\s*identity\)/);assert.match(page,/apiRole\s*===\s*'owner'[^\n]*apiNotes\?\.start/);
assert.match(page,/error\.status === 403\) \{ revokeApiOverview\(error\)/);
console.log('Overview roles hide owner notes for scoped and signed-out users');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx = {};
vm.runInNewContext(fs.readFileSync('docs/editable-search.js', 'utf8'), ctx);
const makeCard = (title, ...values) => ({textContent: title, hidden: false, querySelectorAll: () => values.map(value => ({value}))});
const a = makeCard('Plumbing', 'Maple Co', 'hello@example.test');
const b = makeCard('Electrical', 'Willow Co');
assert.equal(ctx.filterEditableCards([a,b], ' MAPLE '), 1);
assert.equal(a.hidden, false); assert.equal(b.hidden, true);
assert.equal(ctx.filterEditableCards([a,b], 'willow'), 1);
assert.equal(a.hidden, true); assert.equal(b.hidden, false);
assert.equal(ctx.filterEditableCards([a,b], ''), 2);
assert.equal(a.hidden, false); assert.equal(b.hidden, false);
console.log('editable search filters mounted cards and preserves fields');
assert.equal(ctx.normalizeVendor({name:'  ',specialty:'plumbing'}), null, 'blank names are rejected');
const valid=ctx.normalizeVendor({name:'  Example Services  ',specialty:' Plumbing ',contact:'',location:''});
assert.equal(valid.name,'Example Services'); assert.equal(valid.specialty,'Plumbing');
assert.equal(ctx.normalizeVendor({name:'x'.repeat(201)}), null, 'overlong names are rejected');

import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const ctx={}; vm.runInNewContext(readFileSync('docs/property-detail.js','utf8'),ctx);
const room={address:'10 Example St',property_id:42,room_number:2,occupant_present:true,vacant:false,turned:false,rent_ready:false};
const tasks={Requests:[{property_id:42,room_number:2,details:'Fictional repair'},{property_id:42,room_number:3,details:'Other room'},{property_id:77,room_number:2,details:'Other property'}]};
let data=ctx.propertyDetailData(room,{tasks,tasksAuthorized:false,climate:{locations:[]}});
assert.equal(data.tasks.length,0); assert.equal(data.taskState,'Sign in to see private task details.');
data=ctx.propertyDetailData(room,{tasks,tasksAuthorized:true,climate:{locations:[]}});
assert.equal(data.tasks.length,1); assert.equal(data.tasks[0].details,'Fictional repair');
assert.equal(data.presence,'Present'); assert.equal(data.climateState,'No verified climate link for this property.');
const partial=ctx.propertyDetailData({address:'10 Example St',room_number:2},{tasksAuthorized:true,tasks,climate:{locations:[]}});
assert.equal(partial.tasks.length,0); assert.equal(partial.presence,'Unknown'); assert.equal(partial.rentReady,'Not reported');
const exact=ctx.propertyDetailData(room,{tasksAuthorized:true,tasks,climate:{scraped_at:'2026-01-01T00:00:00Z',locations:[{name:'10 Example St',devices:[{temp:73}]}]}});
assert.equal(exact.climate.length,1); assert.equal(exact.climate[0].temp,73);
const ambiguous=ctx.propertyDetailData(room,{climate:{locations:[{name:'10 Example St',devices:[{}]},{name:'10 Example St',devices:[{}]}]}});
assert.equal(ambiguous.climate.length,0);
assert.equal(ctx.propertyDetailData({...room,occupant_present:null},{ }).presence,'Unknown');
assert.equal(ctx.propertyDetailData(room,{tasksAuthorized:true,tasks:{Requests:'bad'}}).taskState,'Private task data unavailable.');
assert.equal(ctx.propertyDetailData({...room,property_id:''},{tasksAuthorized:true,tasks}).taskState,'Task linkage is unavailable for this room.');
console.log('property detail matches only verified room and climate identities');
